mystring[2:]# slicing
print (mystring[2:]) #after2
print (mystring[:3]) #before3
print (mystring[3:6]) #between3and6 and mid
print(mystring[1:3]) #between1and3

print(mystring[::2]) #subslicing (jump2)
print(mystring[2:7:2]) #between2and7 and jump2
print(mystring[::-1]) #reverse string